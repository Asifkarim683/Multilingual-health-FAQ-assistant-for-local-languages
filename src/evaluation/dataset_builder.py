def write_benchmark_files(output_dir: Path = Path("data/eval")):
    """Write unified and per-language CSV test files."""
    output_dir.mkdir(parents=True, exist_ok=True)

    fieldnames = [
        "id", "language", "topic", "question", "gold_source_id", "reference_answer_summary", "split"
    ]

    # 1. Unified CSV
    unified_path = output_dir / "questions.csv"
    with open(unified_path, "w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(FULL_BENCHMARK_QUESTIONS)

    # 2. Per-language files
    for lang in ["en", "hi", "or"]:
        lang_questions = [q for q in FULL_BENCHMARK_QUESTIONS if q["language"] == lang]
        lang_path = output_dir / f"{lang}.csv"
        with open(lang_path, "w", encoding="utf-8", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=fieldnames)
            writer.writeheader()
            writer.writerows(lang_questions)

    print(f"Generated {len(FULL_BENCHMARK_QUESTIONS)} benchmark questions.")
    print(f"Saved unified to {unified_path} and per-language files (en, hi, or).")


if __name__ == "__main__":
    write_benchmark_files()
